const panel = document.querySelector('#detail-panel');
const title = document.querySelector('#detail-title');
const kicker = document.querySelector('#detail-kicker');
const meta = document.querySelector('#detail-meta');
const summary = document.querySelector('#detail-summary');
const responsibilities = document.querySelector('#detail-responsibilities');
const results = document.querySelector('#detail-results');
const links = document.querySelector('#detail-links');
const closeButtons = document.querySelectorAll('[data-close-detail]');
let previousFocus = null;

function renderList(target, items) {
  target.innerHTML = '';
  for (const item of items) {
    const li = document.createElement('li');
    li.textContent = item;
    target.append(li);
  }
}

function renderLinks(items) {
  links.innerHTML = '';
  for (const item of items) {
    if (item.url === '#') {
      const span = document.createElement('span');
      span.textContent = item.label;
      links.append(span);
      continue;
    }

    const link = document.createElement('a');
    link.href = item.url;
    link.textContent = item.label;
    link.target = '_blank';
    link.rel = 'noreferrer';
    links.append(link);
  }
}

function openDetail(id) {
  const detail = resumeData.details[id];

  if (!detail) {
    return;
  }

  previousFocus = document.activeElement;
  kicker.textContent = detail.kicker;
  title.textContent = detail.title;
  meta.textContent = detail.meta;
  summary.textContent = detail.summary;
  renderList(responsibilities, detail.responsibilities);
  renderList(results, detail.results);
  renderLinks(detail.links);

  panel.hidden = false;
  document.body.style.overflow = 'hidden';
  panel.querySelector('.detail-close').focus();
}

function closeDetail() {
  panel.hidden = true;
  document.body.style.overflow = '';

  if (previousFocus) {
    previousFocus.focus();
  }
}

document.querySelectorAll('[data-detail-id]').forEach((trigger) => {
  trigger.addEventListener('click', () => {
    openDetail(trigger.dataset.detailId);
  });
});

closeButtons.forEach((button) => {
  button.addEventListener('click', closeDetail);
});

document.querySelectorAll('a[href="#"]').forEach((link) => {
  link.addEventListener('click', (event) => {
    event.preventDefault();
  });
});

document.addEventListener('keydown', (event) => {
  if (event.key === 'Escape' && !panel.hidden) {
    closeDetail();
  }
});
